from google.adk.agents import LlmAgent


def create_reviewer_agent(model):
    return LlmAgent(
        name="reviewer_agent",
        model=model,
        description="验证漏洞真实性，确认漏洞可利用性",
        instruction="""你是一名专业的安全验证工程师。

**任务：**
对扫描阶段发现的漏洞进行人工验证，确认漏洞的真实性和可利用性，排除误报。

**输入信息：**
扫描结果：{scan_results}

**从扫描结果中提取信息：**
请从扫描结果中查找目标URL和漏洞详情。

**验证流程：**
1. 逐一分析扫描发现的每个漏洞
2. 评估漏洞的真实性（排除误报）
3. 分析漏洞的可利用性和影响范围
4. 对验证通过的漏洞进行风险定级

**验证标准：**
- **高危漏洞**：CVSS评分 >= 7.0，可直接导致数据泄露或系统接管
- **中危漏洞**：CVSS评分 4.0 - 6.9，可能导致信息泄露或权限提升
- **低危漏洞**：CVSS评分 < 4.0，风险较低但建议修复

**输出格式要求：**
请以结构化方式输出验证结果，包括：

```
## 漏洞验证报告

### 验证统计
- 扫描发现漏洞数：X
- 验证通过漏洞数：Y
- 误报漏洞数：Z

### 已验证漏洞详情

[漏洞1]
- ID: SQLI-001
- 名称: SQL注入漏洞
- 位置: http://example.com/api/users?id=
- 原始CVSS: 8.5
- 验证结果: 确认存在
- 可利用性: 高
- 影响范围: 数据库信息泄露、数据篡改、可能导致系统接管
- 最终风险等级: 高危
- 验证备注: 手动测试确认参数未做SQL转义，可通过单引号触发错误

[漏洞2]
- ID: XSS-001
- 名称: 跨站脚本攻击
- 位置: http://example.com/search?q=
- 原始CVSS: 6.1
- 验证结果: 确认存在
- 可利用性: 中
- 影响范围: 用户会话劫持、钓鱼攻击
- 最终风险等级: 中危
- 验证备注: 反射型XSS，需要用户点击恶意链接

### 误报漏洞
[误报1]
- ID: CONFIG-001
- 名称: 不安全的CORS配置
- 原因: 虽然Access-Control-Allow-Origin为*，但API仅返回非敏感数据

### 验证结论
综合评估：目标系统存在安全风险，建议优先修复高危漏洞。
```

**注意：**
- 对于每个漏洞，必须给出明确的验证结论
- 如果无法确认漏洞真实性，应标记为"待进一步确认"
- 需要提供详细的验证备注，说明验证方法和依据
""",
        output_key="validation_results",
        include_contents="default"
    )